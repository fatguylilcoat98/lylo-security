def build_incident_prompt(
    persona_id:          str,
    incident_description: str,
    metadata:            dict,
    image_count:         int = 0,
) -> str:
    """
    Builds the OpenAI prompt to generate the AI Bodyguard Summary section.
    Call this BEFORE generate_tactical_report() — pass the response as
    report_data.bodyguard_summary.

    Tone: Calm. Stern. Focused. No fluff. No generic filler.
    Voice: "Stay safe. Take the photo. I am recording the rest."

    Args:
        persona_id:           The active persona seat
        incident_description: Raw user description of what happened
        metadata:             Dict with timestamp, gps, weather keys
        image_count:          Number of images attached

    Returns:
        A system + user prompt string for a single OpenAI completion call.
    """
    persona_focus = {
        "doctor":   "triage priority, pain indicators, and urgency of medical attention",
        "lawyer":   "legal exposure, preservation of evidence, and silence protocol",
        "wealth":   "consumer rights, financial impact, and dispute escalation path",
        "mechanic": "mechanical failure root cause, safety risk, and repair cost context",
        "guardian": "security threat level, immediate protective actions, and documentation chain",
    }
    focus = persona_focus.get(persona_id, "incident facts and immediate next steps")

    gps_note = ""
    if metadata.get("gps_latitude"):
        gps_note = (
            f"GPS: {metadata['gps_latitude']}, {metadata['gps_longitude']}. "
            f"Address: {metadata.get('gps_address', 'unknown')}."
        )

    weather_note = ""
    if metadata.get("weather_condition"):
        weather_note = (
            f"Weather at time of incident: {metadata['weather_condition']}, "
            f"{metadata.get('weather_temp_f', '?')}°F."
        )

    image_note = (
        f"{image_count} photo(s) have been attached to this report as visual evidence."
        if image_count > 0
        else "No photos attached."
    )

    return f"""
SYSTEM: You are the LYLO OS Bodyguard Council. A protected party has just experienced
an incident and this summary will be printed as a formal record in their Tactical Vault PDF.

Your tone: Calm. Stern. Precise. No filler. No warmth or pleasantries.
Voice model: "Stay safe. Take the photo. I am recording the rest."
Write as if this will be read by a judge, a doctor, or an insurance adjuster.

Your task: Write a 3-5 sentence plain-English summary of this incident.
Focus on: {focus}.
Do NOT use jargon. Do NOT say "It's important to note." Do NOT say "I'm here to help."
State the facts. Name the risks. Give one clear next action.

INCIDENT DATA:
Timestamp: {metadata.get('timestamp', 'Unknown')}
{gps_note}
{weather_note}
{image_note}

USER STATEMENT:
{incident_description}

Write the Bodyguard Summary now. 3-5 sentences. Plain English. Facts only.
""".strip()
