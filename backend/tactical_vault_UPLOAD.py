def generate_tactical_report(report_data: TacticalReportData) -> bytes:
    """
    Generates a high-fidelity Tactical Vault PDF.

    Args:
        report_data: Fully populated TacticalReportData instance.

    Returns:
        Raw PDF bytes — write to file or stream as HTTP response.

    Usage:
        pdf_bytes = generate_tactical_report(data)
        # Stream as FastAPI response:
        return Response(content=pdf_bytes, media_type="application/pdf",
                        headers={"Content-Disposition": "attachment; filename=lylo_report.pdf"})
    """
    buf    = io.BytesIO()
    W, H   = letter
    margin = 0.5 * inch

    # Unique report ID
    import hashlib, time
    report_id = hashlib.md5(
        f"{report_data.user_email}{time.time()}".encode()
    ).hexdigest()[:10].upper()

    doc = SimpleDocTemplate(
        buf,
        pagesize       = letter,
        leftMargin     = margin,
        rightMargin    = margin,
        topMargin      = 0.65 * inch,    # Leaves room for accent stripe
        bottomMargin   = 0.65 * inch,
        title          = f"LYLO Tactical Vault — {report_data.incident_title}",
        author         = "LYLO OS Tactical Vault",
        subject        = PERSONA_LABELS.get(report_data.persona_id, "Incident Report"),
        creator        = "LYLO OS v31.0",
    )

    accent  = PERSONA_COLORS.get(report_data.persona_id, PERSONA_COLORS["default"])
    s       = _build_styles()
    story   = []

    page_canvas_fn = _DarkPageCanvas(
        persona_id = report_data.persona_id,
        user_name  = report_data.user_name,
        report_id  = report_id,
    )

    # ── Page 1: Cover + Metadata + Bodyguard Summary ─────────────────────────
    _build_cover_block(report_data, s, accent, story)
    _build_metadata_block(report_data, s, accent, story)
    _build_bodyguard_summary(report_data, s, accent, story)

    # For personas that don't have a dedicated section, embed images on page 1
    if report_data.persona_id not in ("doctor", "lawyer", "wealth", "mechanic"):
        _build_images_block(report_data, s, accent, story)
        if report_data.incident_description:
            _section_header("INCIDENT DESCRIPTION", s, story)
            story.append(Paragraph(report_data.incident_description, s["body"]))

    # ── Page 2+: Persona-Specific Section ───────────────────────────────────
    persona = report_data.persona_id
    if persona == "doctor":
        _build_doctor_section(report_data, s, accent, story)
    elif persona == "lawyer":
        _build_lawyer_section(report_data, s, accent, story)
    elif persona == "wealth":
        _build_wealth_section(report_data, s, accent, story)
    elif persona == "mechanic":
        _build_mechanic_section(report_data, s, accent, story)

    # ── Final page: Certification footer ────────────────────────────────────
    story.append(PageBreak())
    story.append(Spacer(1, 1.5 * inch))
    _divider(accent, story)
    story.append(Spacer(1, 0.2 * inch))

    cert_lines = [
        f"This report was generated by LYLO OS Tactical Vault (Elite Tier).",
        f"Report ID: {report_id}",
        f"Protected Party: {report_data.user_name}",
        f"Generated: {datetime.now(timezone.utc).strftime('%B %d, %Y at %I:%M %p UTC')}",
        f"",
        f"All metadata in this document was recorded automatically at the time of incident.",
        f"This document may be used as contemporaneous evidence in legal, medical,",
        f"insurance, or consumer protection proceedings.",
        f"",
        f"LYLO OS — No one gets left behind.",
    ]
    for line in cert_lines:
        story.append(Paragraph(line, s["footer"] if not line.startswith("LYLO") else ParagraphStyle(
            "cert_brand", fontName="Helvetica-Bold", fontSize=9,
            textColor=accent, alignment=TA_CENTER
        )))
        story.append(Spacer(1, 3))

    doc.build(story, onFirstPage=page_canvas_fn, onLaterPages=page_canvas_fn)
    return buf.getvalue()


