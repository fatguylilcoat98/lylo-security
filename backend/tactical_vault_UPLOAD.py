class _DarkPageCanvas:
    """
    Wraps reportlab's canvas to draw a dark background, colored header stripe,
    and footer on every page.
    """
    def __init__(self, persona_id: str, user_name: str, report_id: str):
        self.persona_id  = persona_id
        self.user_name   = user_name
        self.report_id   = report_id
        self.accent      = PERSONA_COLORS.get(persona_id, PERSONA_COLORS["default"])

    def __call__(self, c: rl_canvas.Canvas, doc):
        W, H = letter
        c.saveState()

        # Full-page dark background
        c.setFillColor(LYLO_BLACK)
        c.rect(0, 0, W, H, fill=1, stroke=0)

        # Top accent stripe
        c.setFillColor(self.accent)
        c.rect(0, H - 0.35 * inch, W, 0.35 * inch, fill=1, stroke=0)

        # LYLO OS label in stripe
        c.setFillColor(LYLO_BLACK)
        c.setFont("Helvetica-Bold", 8)
        c.drawString(0.5 * inch, H - 0.24 * inch, "LYLO OS  ·  TACTICAL VAULT  ·  ELITE TIER")

        # Report ID top-right
        c.setFont("Helvetica", 7)
        c.drawRightString(W - 0.5 * inch, H - 0.24 * inch, f"ID: {self.report_id}")

        # Bottom footer line
        c.setStrokeColor(LYLO_GRAY_M)
        c.setLineWidth(0.5)
        c.line(0.5 * inch, 0.45 * inch, W - 0.5 * inch, 0.45 * inch)

        # Footer text
        c.setFillColor(LYLO_GRAY_T)
        c.setFont("Helvetica", 7)
        ts = datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M UTC")
        c.drawString(0.5 * inch, 0.28 * inch,
                     f"CONFIDENTIAL — {self.user_name.upper()} — Generated {ts}")
        c.drawRightString(W - 0.5 * inch, 0.28 * inch,
                          f"Page {doc.page}")

        c.restoreState()


