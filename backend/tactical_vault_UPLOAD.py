def send_report_to_pro(
    pdf_bytes:        bytes,
    recipient_email:  str,
    sender_name:      str,
    persona_id:       str,
    subject_override: Optional[str]  = None,
    incident_title:   str            = "Incident Report",
    user_email:       str            = "",
) -> bool:
    """
    Emails the Tactical Vault PDF to a third-party professional
    (lawyer, doctor, insurance agent, etc.) with a single call.

    Requires these environment variables:
        SMTP_HOST       e.g. "smtp.gmail.com"
        SMTP_PORT       e.g. "587"
        SMTP_USER       The sending email address (your system email)
        SMTP_PASSWORD   App password or SMTP credential

    Args:
        pdf_bytes:        Raw PDF bytes from generate_tactical_report()
        recipient_email:  The pro's email address
        sender_name:      The user's display name (for the email body)
        persona_id:       Determines report label in email body
        subject_override: Optional custom subject line
        incident_title:   Incident name for subject line
        user_email:       User's email (for Reply-To header)

    Returns:
        True on successful send, False on failure.
    """
    smtp_host = os.getenv("SMTP_HOST", "smtp.gmail.com")
    smtp_port = int(os.getenv("SMTP_PORT", "587"))
    smtp_user = os.getenv("SMTP_USER", "")
    smtp_pass = os.getenv("SMTP_PASSWORD", "")

    if not smtp_user or not smtp_pass:
        log.error("[Vault] SMTP credentials not configured — set SMTP_USER and SMTP_PASSWORD.")
        return False

    report_label = PERSONA_LABELS.get(persona_id, "TACTICAL INCIDENT REPORT")
    subject = subject_override or (
        f"LYLO OS — {report_label}: {incident_title} — Sent by {sender_name}"
    )

    # ── Email body ────────────────────────────────────────────────────────────
    body_text = f"""
{report_label}
Sent via LYLO OS Tactical Vault — Elite Tier

From:    {sender_name}
Re:      {incident_title}

This report was generated automatically by LYLO OS at the time of the incident.
It contains:
  - User personal context and emergency contact
  - GPS coordinates, timestamp, and weather metadata
  - High-resolution photographic evidence
  - AI-generated plain-English incident summary
  - {report_label.title()} analysis and recommended next steps

This document is intended for your professional review as part of the
ongoing matter referenced above.

For questions, contact {sender_name} directly (Reply-To included).

—
LYLO OS Tactical Vault
Elite Tier — Confidential Document
""".strip()

    # ── Assemble MIME message ─────────────────────────────────────────────────
    msg = MIMEMultipart()
    msg["From"]     = f"LYLO OS Tactical Vault <{smtp_user}>"
    msg["To"]       = recipient_email
    msg["Subject"]  = subject
    if user_email:
        msg["Reply-To"] = user_email

    msg.attach(MIMEText(body_text, "plain"))

    # Attach PDF
    filename = (
        f"LYLO_TacticalVault_{persona_id.upper()}_"
        f"{incident_title.replace(' ', '_')[:30]}.pdf"
    )
    attachment = MIMEBase("application", "octet-stream")
    attachment.set_payload(pdf_bytes)
    encoders.encode_base64(attachment)
    attachment.add_header(
        "Content-Disposition", f'attachment; filename="{filename}"'
    )
    msg.attach(attachment)

    # ── Send ─────────────────────────────────────────────────────────────────
    try:
        context = ssl.create_default_context()
        with smtplib.SMTP(smtp_host, smtp_port) as server:
            server.ehlo()
            server.starttls(context=context)
            server.login(smtp_user, smtp_pass)
            server.sendmail(smtp_user, recipient_email, msg.as_string())
        log.info(
            f"[Vault] Report sent to {recipient_email[:4]}*** "
            f"persona={persona_id} incident='{incident_title[:40]}'"
        )
        return True
    except Exception as e:
        log.error(f"[Vault] send_report_to_pro failed: {e}")
        return False


