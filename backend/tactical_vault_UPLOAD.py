def _divider(accent: colors.HexColor, story: list):
    story.append(Spacer(1, 6))
    story.append(HRFlowable(width="100%", thickness=0.5,
                            color=accent, spaceAfter=4))


def _section_header(title: str, s: dict, story: list):
    story.append(Paragraph(title.upper(), s["section_header"]))


def _kv_table(pairs: list[tuple[str, str]], s: dict,
               accent: colors.HexColor) -> Table:
    """
    Renders a two-column key/value table with dark styling.
    pairs: list of (label, value) tuples
    """
    data = []
    for label, value in pairs:
        data.append([
            Paragraph(label.upper(), s["label"]),
            Paragraph(str(value) if value else "—", s["value"]),
        ])

    col_widths = [1.6 * inch, 5.4 * inch]
    t = Table(data, colWidths=col_widths, hAlign="LEFT")
    t.setStyle(TableStyle([
        ("BACKGROUND",  (0, 0), (-1, -1), LYLO_GRAY_D),
        ("ROWBACKGROUNDS", (0, 0), (-1, -1), [LYLO_GRAY_D, LYLO_GRAY_M]),
        ("LEFTPADDING",  (0, 0), (-1, -1), 10),
        ("RIGHTPADDING", (0, 0), (-1, -1), 10),
        ("TOPPADDING",   (0, 0), (-1, -1), 7),
        ("BOTTOMPADDING",(0, 0), (-1, -1), 7),
        ("LINEBELOW",    (0, 0), (-1, -1), 0.3, LYLO_GRAY_L),
        ("BOX",          (0, 0), (-1, -1), 0.5, accent),
        ("VALIGN",       (0, 0), (-1, -1), "TOP"),
    ]))
    return t


def _build_cover_block(data: TacticalReportData, s: dict,
                        accent: colors.HexColor, story: list):
    """Cover section: persona label, incident title, user context."""
    persona_label = PERSONA_LABELS.get(data.persona_id, PERSONA_LABELS["default"])
    persona_icon  = PERSONA_ICONS.get(data.persona_id, PERSONA_ICONS["default"])

    story.append(Spacer(1, 0.2 * inch))

    # Persona seat label
    story.append(Paragraph(persona_icon, s["report_subtitle"]))
    story.append(Spacer(1, 4))

    # Main incident title
    story.append(Paragraph(data.incident_title or "Incident Report", s["report_title"]))
    story.append(Spacer(1, 2))
    story.append(Paragraph(persona_label, s["report_subtitle"]))
    story.append(Spacer(1, 0.15 * inch))
    _divider(accent, story)

    # User + emergency contact
    _section_header("PROTECTED PARTY", s, story)
    pairs = [
        ("Name",              data.user_name),
        ("Contact Email",     data.user_email or "—"),
        ("Emergency Contact", data.emergency_contact_name or "—"),
        ("Emergency Phone",   data.emergency_contact_phone or "—"),
    ]
    story.append(_kv_table(pairs, s, accent))


def _build_metadata_block(data: TacticalReportData, s: dict,
                           accent: colors.HexColor, story: list):
    """Auto-collected GPS, timestamp, weather metadata."""
    _section_header("INCIDENT METADATA — AUTO-RECORDED", s, story)

    # Format timestamp
    ts_display = data.timestamp
    if ts_display:
        try:
            dt = datetime.fromisoformat(data.timestamp.replace("Z", "+00:00"))
            ts_display = dt.strftime("%B %d, %Y at %I:%M %p UTC")
        except Exception:
            pass

    # GPS line
    gps_display = "—"
    if data.gps_latitude and data.gps_longitude:
        gps_display = f"{data.gps_latitude}, {data.gps_longitude}"
        if data.gps_address:
            gps_display += f"  ·  {data.gps_address}"

    # Weather
    weather_display = "—"
    if data.weather_condition:
        weather_display = data.weather_condition
        if data.weather_temp_f:
            weather_display += f"  ·  {data.weather_temp_f}°F"

    pairs = [
        ("Timestamp",  ts_display or "—"),
        ("GPS",        gps_display),
        ("Weather",    weather_display),
        ("Device",     data.device_model or "—"),
    ]
    story.append(_kv_table(pairs, s, accent))


def _build_bodyguard_summary(data: TacticalReportData, s: dict,
                              accent: colors.HexColor, story: list):
    """AI-generated plain-English incident summary."""
    if not data.bodyguard_summary:
        return

    _section_header("BODYGUARD SUMMARY — AI ANALYSIS", s, story)

    # Bordered card for the summary
    summary_text = data.bodyguard_summary.replace("\n", "<br/>")
    summary_para = Paragraph(summary_text, s["bodyguard_summary"])

    card = Table(
        [[summary_para]],
        colWidths=[7.0 * inch],
    )
    card.setStyle(TableStyle([
        ("BACKGROUND",   (0, 0), (-1, -1), LYLO_GRAY_D),
        ("BOX",          (0, 0), (-1, -1), 1.0, accent),
        ("LEFTPADDING",  (0, 0), (-1, -1), 14),
        ("RIGHTPADDING", (0, 0), (-1, -1), 14),
        ("TOPPADDING",   (0, 0), (-1, -1), 12),
        ("BOTTOMPADDING",(0, 0), (-1, -1), 12),
        ("LINEABOVE",    (0, 0), (-1, 0),  2.0, accent),
    ]))
    story.append(card)
    story.append(Spacer(1, 8))


def _build_images_block(data: TacticalReportData, s: dict,
                         accent: colors.HexColor, story: list):
    """Embeds high-res images with captions."""
    if not data.image_bytes_list:
        return

    _section_header(f"VISUAL EVIDENCE — {len(data.image_bytes_list)} IMAGE(S) ATTACHED", s, story)

    for i, img_bytes in enumerate(data.image_bytes_list):
        caption = (data.image_captions[i]
                   if i < len(data.image_captions)
                   else f"Evidence Photo {i + 1}")
        try:
            img_buf = io.BytesIO(img_bytes)
            rl_img  = RLImage(img_buf, width=6.5 * inch, height=4.0 * inch,
                              kind="proportional")

            # Border frame
            img_table = Table([[rl_img]], colWidths=[6.6 * inch])
            img_table.setStyle(TableStyle([
                ("BACKGROUND",    (0, 0), (-1, -1), LYLO_GRAY_D),
                ("BOX",           (0, 0), (-1, -1), 1.0, accent),
                ("ALIGN",         (0, 0), (-1, -1), "CENTER"),
                ("TOPPADDING",    (0, 0), (-1, -1), 8),
                ("BOTTOMPADDING", (0, 0), (-1, -1), 8),
            ]))
            story.append(img_table)
            story.append(Paragraph(
                f"FIGURE {i + 1}: {caption.upper()}", s["caption"]
            ))
        except Exception as e:
            log.warning(f"[Vault] Image {i + 1} embed failed: {e}")
            story.append(Paragraph(
                f"[Image {i + 1} could not be embedded — file may be corrupted]",
                s["body_muted"]
            ))


