def _build_doctor_section(data: TacticalReportData, s: dict,
                           accent: colors.HexColor, story: list):
    story.append(PageBreak())
    _section_header("CLINICAL TRIAGE SUMMARY", s, story)

    # Pain assessment card
    pairs = [
        ("Pain Scale",      f"{data.pain_scale} / 10" if data.pain_scale else "—"),
        ("Duration",        data.pain_duration or "—"),
        ("Location",        data.pain_location or "—"),
        ("Prior Conditions", data.prior_conditions or "None reported"),
    ]
    story.append(_kv_table(pairs, s, accent))

    # Symptoms list
    if data.symptoms:
        _section_header("REPORTED SYMPTOMS", s, story)
        for i, symptom in enumerate(data.symptoms, 1):
            story.append(Paragraph(f"{i}. {symptom}", s["body"]))
        story.append(Spacer(1, 6))

    # Incident description
    if data.incident_description:
        _section_header("PATIENT STATEMENT", s, story)
        story.append(Paragraph(data.incident_description, s["body"]))

    # Visual evidence
    _build_images_block(data, s, accent, story)

    # Doctor advisory
    _divider(accent, story)
    story.append(Paragraph(
        "ADVISORY: This report documents the patient's self-reported symptoms at the "
        "time of the incident. It is not a clinical diagnosis. Present this document "
        "to your physician or ER staff as a first-contact triage brief.",
        s["body_muted"]
    ))


def _build_lawyer_section(data: TacticalReportData, s: dict,
                           accent: colors.HexColor, story: list):
    story.append(PageBreak())
    _section_header("LEGAL EVIDENCE CHAIN", s, story)

    pairs = [
        ("Opposing Party",      data.opposing_party or "—"),
        ("Police Report No.",   data.police_report_number or "Not filed"),
        ("Silence Protocol",    "ACTIVATED — No statements made to opposing party"
                                if data.silence_protocol_used
                                else "Not activated — review statements made"),
    ]
    story.append(_kv_table(pairs, s, accent))

    # Witnesses
    if data.witness_names:
        _section_header("WITNESS REGISTRY", s, story)
        for i, w in enumerate(data.witness_names, 1):
            story.append(Paragraph(f"{i}. {w}", s["body"]))
        story.append(Spacer(1, 6))

    # Incident narrative
    if data.incident_description:
        _section_header("INCIDENT NARRATIVE — CLIENT STATEMENT", s, story)
        story.append(Paragraph(data.incident_description, s["body"]))

    # Visual evidence
    _build_images_block(data, s, accent, story)

    # Silence Protocol box
    story.append(PageBreak())
    _section_header("SILENCE PROTOCOL", s, story)
    silence_lines = [
        "1. Do NOT give a recorded statement to any insurance adjuster without counsel.",
        "2. Do NOT sign any release or settlement document at the scene.",
        "3. Do NOT discuss fault, apologize, or speculate about the incident.",
        "4. Direct all parties to your attorney for any questions.",
        "5. Preserve this document as your contemporaneous record of events.",
    ]
    for line in silence_lines:
        story.append(Paragraph(line, s["body"]))

    _divider(accent, story)
    story.append(Paragraph(
        "ADVISORY: This dossier is prepared under attorney-client privilege guidelines "
        "for the sole use of the named party. It is not legal advice. Retain a licensed "
        "attorney to review before taking any legal action.",
        s["body_muted"]
    ))


