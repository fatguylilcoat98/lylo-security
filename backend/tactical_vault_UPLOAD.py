@dataclass
class TacticalReportData:
    """
    All data needed to generate a Tactical Vault PDF.
    Passed from the /generate-report FastAPI endpoint.
    """
    # ── User Context ─────────────────────────────────────────────────────────
    user_name:              str   = "Unknown"
    user_email:             str   = ""
    emergency_contact_name: str   = ""
    emergency_contact_phone: str  = ""

    # ── Incident ─────────────────────────────────────────────────────────────
    persona_id:             str   = "guardian"
    incident_title:         str   = "Incident Report"
    incident_description:   str   = ""

    # ── Metadata (auto-collected by frontend) ─────────────────────────────────
    timestamp:              str   = ""          # ISO string, e.g. "2025-02-24T14:33:00Z"
    gps_latitude:           str   = ""
    gps_longitude:          str   = ""
    gps_address:            str   = ""
    weather_condition:      str   = ""
    weather_temp_f:         str   = ""
    device_model:           str   = ""

    # ── AI Bodyguard Summary ─────────────────────────────────────────────────
    bodyguard_summary:      str   = ""          # Pre-generated by OpenAI before PDF call

    # ── Persona-Specific Fields ───────────────────────────────────────────────
    # Doctor
    pain_scale:             str   = ""          # 1-10
    pain_duration:          str   = ""
    pain_location:          str   = ""
    symptoms:               list  = field(default_factory=list)
    prior_conditions:       str   = ""

    # Lawyer
    witness_names:          list  = field(default_factory=list)
    opposing_party:         str   = ""
    police_report_number:   str   = ""
    silence_protocol_used:  bool  = True

    # Wealth
    merchant_name:          str   = ""
    transaction_amount:     str   = ""
    dispute_reason:         str   = ""
    consumer_rights_note:   str   = ""

    # Mechanic
    vehicle_year:           str   = ""
    vehicle_make:           str   = ""
    vehicle_model:          str   = ""
    obd_codes:              list  = field(default_factory=list)
    dealer_quote:           str   = ""
    fair_market_estimate:   str   = ""
    repair_description:     str   = ""

    # ── Images ────────────────────────────────────────────────────────────────
    image_bytes_list:       list  = field(default_factory=list)  # list of bytes objects
    image_captions:         list  = field(default_factory=list)  # parallel list of caption strings


